// Задание 2: "Расчет возраста питомца"
// Cоздайте функцию, которая преобразует возраст собаки в "человеческие" годы.
// До 2 лет каждый год собаки равен 10.5 человеческим годам, после - каждый год равен 4 человеческим годам.
// Результат распечатай в консоль.

fun dogAgeToHuman(dogAge: Double) {
    val humanAge: Double
    if (dogAge <= 2.0) {
        humanAge = dogAge * 10.5
    } else {
        humanAge =  2 * 10.5 + (dogAge - 2.0) * 4.0
    }
    println("Возраст собаки в человеческих годах: $humanAge")
}
