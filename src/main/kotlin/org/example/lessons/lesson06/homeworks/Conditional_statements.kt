//Создайте функцию, которая конвертирует температуру из градусов Цельсия в Фаренгейты и наоборот в зависимости
//от указанной единицы измерения (C/F).
//Единицу измерения нужно передать вторым аргументом функции. Несколько аргументов передаются через запятую.
//Распечатай в консоль результат конвертации с добавлением единицы измерения.
//Чтобы добавить единицу измерения после результата используй функцию печати без переноса строки print("C")
//или print("F").
fun convertTemperature(value: Double, unit: String) {
    when (unit.uppercase()){
        "C" -> {
            val convertValue = value * 9/ 5 + 32
            print(convertValue)
            print("F")
        }
        "F" -> {
            val convertValue = (value - 32) * 5 / 9
            print(convertValue)
            print("C")
        }
        else -> println("Неизвестная единица измерения")
    }
}

