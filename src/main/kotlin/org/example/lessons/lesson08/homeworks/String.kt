//Напишите шифратор/дешифратор для строки. Шифровка производится путём замены двух соседних букв между собой:
//Kotlin шифруется в oKltni. Дешифровка выполняется аналогично.
//
//Если длина строки - нечётная, в конец добавляется символ пробела до начала шифрования. Таким образом все шифрованные
//сообщения будут с чётной длинной. Должно получиться два публичных метода: encrypt() и decrypt() которые принимают
//строку и печатают результат в консоль.
fun encrypt(str : String) : String{
    var str2 = str
    var newStr = ""
    if (str.length % 2 != 0){
        str2 = str + " "
    }
    for (i in 1 .. str2.length step 2){
        newStr =newStr + str2[i] + str[i-1]
    }
    return newStr
}

fun decrypt(str : String) : String{
    var newStr = ""
    for (i in 1 .. str.length step 2){
        newStr = newStr + str[i] + str[i-1]
    }
    return newStr
}

