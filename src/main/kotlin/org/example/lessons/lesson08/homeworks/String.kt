//Если фраза заканчивается на "без проблем":
//Преобразование: Замените "без проблем" на "с парой интересных вызовов на пути".
//Если фраза содержит только одно слово:
//Преобразование: Добавьте перед словом "Иногда," и после слова ", но не всегда".
//Примеры Тестовых Фраз:
//
//"Это невозможно выполнить за один день"
//"Я не уверен в успехе этого проекта"
//"Произошла катастрофа на сервере"
//"Этот код работает без проблем"
//"Удача"

fun transformPhrase (str : String) : String {
    val words = str.trim().split(" ")
    val newStr = when {
        str.contains("невозможно", true) -> str.replace("невозможно", "совершенно точно возможно, просто требует времени")
        str.startsWith("Я не уверен") -> "$str, но моя интуиция говорит об обратном"
        str.contains("катастрофа", true) -> str.replace("катастрофа", "интересное событие")
        str.endsWith("без проблем") -> str.replace("без проблем", "с парой интересных вызовов на пути")
        words.size == 1  ->  "Иногда, $str, но не всегда"
        else -> str
    }
    return newStr
}

